std::vector<std::byte> unhex(std::string_view text) {
  auto bytes = std::vector<std::byte>{};
  for (std::size_t i = 0; i < text.size(); i += 2)
    bytes.push_back(static_cast<std::byte>(std::stoul(std::string{text.substr(i, 2)}, nullptr, 16)));
  return bytes;
}
